<script lang="ts">
	import { type Metadata } from '$lib';
	import texts from '$lib/assets/texts.json';
	import { typedKeys } from '$lib/helpers';
	import { app } from '$lib/state.svelte';
	import { fonts } from '../../fonts';

	// let app.activePreview = $state<keyof typeof texts | 'charset'>(typedKeys(texts)[0]);
	const charset = `!"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_\`abcdefghijklmnopqrstuvwxyz{|}~`;
	let extMeta = $state<{ [key: string]: { characterSet: number[] } } | null>(null);
	let meta = $state<Metadata>();
	import('$lib/assets/metadata.json').then((m) => {
		meta = m.default;
	});
	import('$lib/assets/extended-metadata.json').then((ext) => {
		extMeta = ext.default;
	});

	let settings = $state<{
		[key: string]: {
			features: string[];
			axes: {
				[key: string]: number | 'null';
			};
		};
	}>(
		fonts.reduce((acc, curr) => {
			acc[curr.name] = { features: [], axes: {} };
			return acc;
		}, {})
	);

	let fontFeatureSettings = $derived(
		settings[app.activeFont].features.map((v) => `"${v}"`).join(', ')
	);

	let fontVariationSettings = $derived.by(() => {
		let acc = '';
		const axes = settings[app.activeFont].axes;
		const axesNames = Object.keys(axes);
		for (const axis of axesNames) {
			if (acc !== '') acc += ', ';
			if (axis !== null) acc += `"${axis}" ${settings[app.activeFont].axes[axis]}`;
		}
		return acc;
	});
</script>

<div
	id="preview"
	style="--preview-font: {app.activeFont}; --preview-font-subset: {app.activeFont} Subset;"
>
	<ul id="preview-toggles">
		<li>
			<label>
				<input type="radio" name="preview" value={'charset'} bind:group={app.activePreview} />
				<span>charset</span>
			</label>
		</li>
		{#each typedKeys(texts) as key}
			<li>
				<label>
					<input type="radio" name="preview" value={key} bind:group={app.activePreview} />
					<span>{key}</span>
				</label>
			</li>
		{/each}
	</ul>
	{#snippet structuredPreview(selectedText: { text: string; quotes?: boolean })}
		{@const text = selectedText.text}
		<div
			id="preview-text"
			class="preview"
			class:quotes={selectedText.quotes}
			style="font-feature-settings: {fontFeatureSettings};
        font-variation-settings: {fontVariationSettings};
        "
		>
			<p class="dropcap">
				{text.slice(0, text.indexOf(' '))}
			</p>
			<p>{text.slice(text.indexOf(' ') + 1)}</p>
		</div>
	{/snippet}
	{fontVariationSettings}
	{#if app.activePreview === 'charset'}
		<p>Autogenerated character set. Missing glyphs are hidden with the font Adobe Blank.</p>
		<div
			id="preview-charset"
			class="preview"
			style="font-feature-settings: {fontFeatureSettings};
        font-variation-settings: {fontVariationSettings};
        "
		>
			{#if extMeta && extMeta?.[app.activeFont]?.characterSet}
				{#each String.fromCodePoint(...extMeta[app.activeFont].characterSet) as char}
					<span>{char}</span>
				{/each}
				<!-- <p>{String.fromCodePoint(...extMeta[app.activeFont].characterSet)}</p> -->
			{:else}
				ERR
				{#each charset.split('') as char}
					{char}
				{/each}
			{/if}
		</div>
	{:else}
		{@render structuredPreview(texts[app.activePreview])}
	{/if}
</div>
<div id="preview-settings">
	<ul id="feature-settings">
		{#if meta}
			{@const faces = meta[app.activeFont]}
			{#each Object.keys(faces) as faceName}
				{@const face = faces[faceName]}
				{#each face.availableFeatures as feature}
					<label>
						<input
							type="checkbox"
							name="{app.activeFont}-features"
							value={feature}
							bind:group={settings[app.activeFont].features}
						/>
						{feature}
					</label>
				{/each}
				{#each Object.keys(face.variationAxes) as axisName}
					{@const axis = face.variationAxes[axisName]}
					<form>
						<label
							>{axisName}
							<input
								type="range"
								name="{app.activeFont}-axis"
								min={axis.min}
								max={axis.max}
								oninput={(e) => {
									settings[app.activeFont].axes[axisName] = e.target.value;
								}}
							/>
						</label>
						<button
							type="reset"
							onclick={() => {
								settings[app.activeFont].axes[axisName] = 'null';
							}}>Reset</button
						>
					</form>
				{/each}
			{/each}
		{/if}
	</ul>
</div>

