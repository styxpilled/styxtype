<script lang="ts">
	import { type Metadata } from '$lib';
	import texts from '$lib/assets/texts.json';
	import { typedKeys } from '$lib/helpers';
	import { app } from '$lib/state.svelte';
	import { UnicodeRange } from '@japont/unicode-range';
	import { fonts } from '../../fonts';
	import Meta from './Preview/Meta.svelte';

	// let app.activePreview = $state<keyof typeof texts | 'charset'>(typedKeys(texts)[0]);
	const charset = `!"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_\`abcdefghijklmnopqrstuvwxyz{|}~`;
	let extMeta = $state<{ [key: string]: { characterSet: string[] } } | null>(null);
	let meta = $state<Metadata>();
	import('$lib/assets/metadata.json').then((m) => {
		meta = m.default;
	});
	import('$lib/assets/extended-metadata.json').then((ext) => {
		extMeta = ext.default;
	});

	let settings = $state({
		size: {
			value: 48,
			min: 12,
			max: 150
		},
		lineHeight: {
			value: 1,
			min: 0.25,
			max: 3,
			step: 0.25
		},
		letterSpacing: {
			value: 0,
			min: -20,
			max: 20
		}
	});
	let featureSettings = $state<{
		[key: string]: {
			features: string[];
			axes: {
				[key: string]: number | 'null';
			};
		};
	}>(
		fonts.reduce((acc, curr) => {
			acc[curr.name] = { features: [], axes: {} };
			return acc;
		}, {})
	);

	let fontFeatureSettings = $derived(
		featureSettings[app.activeFont].features.map((v) => `"${v}" 1`).join(', ')
	);

	let fontVariationSettings = $derived.by(() => {
		let acc = '';
		const axes = featureSettings[app.activeFont].axes;
		const axesNames = Object.keys(axes);
		for (const axis of axesNames) {
			if (acc !== '') acc += ', ';
			if (axes[axis] !== null) acc += `"${axis}" ${axes[axis]}`;
		}
		return acc;
	});
</script>

<div
	id="preview"
	style="--preview-font: {app.activeFont}; --preview-font-subset: {app.activeFont} Subset;"
>
	<ul id="preview-toggles">
		<!-- {@render previewToggle('charset')} -->
		<!-- {@render previewToggle('typetest')} -->
		{#each ['charset', 'typetest'].concat(typedKeys(texts)) as (typeof app.activePreview)[] as value}
			<li>
				<label>
					<input
						type="radio"
						name="preview"
						{value}
						checked={app.activePreview === value}
						oninput={() => (app.activePreview = value)}
					/>
					<span>{value}</span>
				</label>
			</li>
		{/each}
	</ul>
	{#snippet structuredPreview(selectedText: { text: string; quotes?: boolean })}
		{@const text = selectedText.text}
		<div
			id="preview-text"
			class="preview"
			class:quotes={text.charAt(0) == '“'}
			style:font-feature-settings={fontFeatureSettings}
			style:font-variation-settings={fontVariationSettings}
		>
			<p class="dropcap">
				{#if text.charAt(0) == '“'}
					<span>“</span>{text.slice(1, text.indexOf(' '))}
				{:else}
					{text.slice(0, text.indexOf(' '))}
				{/if}
			</p>
			<p>{text.slice(text.indexOf(' ') + 1)}</p>
		</div>
	{/snippet}
	<div
		id="preview-container"
		style="font-family: '{app.activeFont} Subset', '{app.activeFont}', 'AdobeBlank Preview', 'AdobeBlank';"
	>
		{#if app.activePreview === 'charset'}
			<p class="charset-info">
				Autogenerated character set. Missing glyphs are hidden with the font Adobe Blank.
			</p>
			<div
				id="preview-charset"
				class="preview"
				style:font-feature-settings={fontFeatureSettings}
				style:font-variation-settings={fontVariationSettings}
			>
				{#if extMeta && extMeta?.[app.activeFont]?.characterSet}
					{#each String.fromCodePoint(...UnicodeRange.parse(extMeta[app.activeFont].characterSet)) as char}
						<span>{char}</span>
					{/each}
				{:else}
					Can't load character set, defaulting to standard...
					{#each charset.split('') as char}
						{char}
					{/each}
				{/if}
			</div>
		{:else if app.activePreview === 'typetest'}
			<div
				id="preview-text"
				class="preview"
				style:font-feature-settings={fontFeatureSettings}
				style:font-variation-settings={fontVariationSettings}
				style:font-size="{settings.size.value}pt"
				style:line-height="{settings.lineHeight.value}em"
				style:letter-spacing="{settings.letterSpacing.value}px"
				contenteditable="true"
				spellcheck="false"
			>
				Lorem, ipsum dolor sit amet consectetur adipisicing elit. Minus, alias.
			</div>
		{:else}
			{@render structuredPreview(texts[app.activePreview])}
		{/if}
	</div>
</div>
{#if meta}
	{@const faces = meta[app.activeFont]}
	<Meta {faces} bind:featureSettings bind:settings />
{:else}
	<Meta faces={{}} />
{/if}

